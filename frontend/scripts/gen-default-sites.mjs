// Regenerates src/data/defaultSites.ts from data/regions.json.
//
// The three published candidate sites were a hand-typed copy of the dataset,
// and a copy goes stale. When the thirty conflicts between the demo numbers and
// the July collection were settled, this file still held Northern Virginia's
// land at $420,000 an acre against the dataset's $4.4M, and Nordic Hydro's
// build cost at $10,200 a kW against $12,295. The home page and the results
// screen read from here, so the worked example would have argued against the
// data behind it. That is the same failure as the interconnection panel.
//
// Run from the frontend folder:  node scripts/gen-default-sites.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const regions = JSON.parse(readFileSync(resolve(here, '../../data/regions.json'), 'utf8'))

// Place names are the only thing here the dataset does not carry.
const SITES = [
  { key: 'eu-nordic-hydro', label: 'Nordic Hydro',      place: 'Luleå and Boden, Sweden' },
  { key: 'us-tx-ercot',     label: 'Texas ERCOT',        place: 'Hays County, Texas' },
  { key: 'us-va-northern',  label: 'Northern Virginia',  place: 'Loudoun County, Virginia' },
]

const FIELDS = [
  ['powerRate',         'power_rate_usd_per_kwh',     0],
  ['waterRate',         'water_rate_usd_per_kgal',    0],
  ['landCostPerAcre',   'land_cost_per_acre_usd',     0],
  ['constructionPerKw', 'construction_cost_per_kw',   0],
  ['staffIndex',        'staff_cost_index',           1],
  ['taxRate',           'tax_rate',                   0],
  ['taxAbatementYears', 'tax_abatement_years',        0],
  ['incentivePerKw',    'incentive_usd_per_kw',       0],
]

const NULLABLE = [
  ['riskScore',     'risk_score'],
  ['renewablePct',  'renewable_pct'],
  ['latencyMs',     'latency_ms_to_hub'],
  ['gridWaitYears', 'grid_interconnection_years'],
]

const lines = []
for (const site of SITES) {
  const r = regions[site.key]
  if (!r) throw new Error(`gen-default-sites: ${site.key} is not in data/regions.json`)

  const base = []
  for (const [name, driver, fallback] of FIELDS) {
    const v = r[driver]?.value
    base.push(`${name}: ${v === null || v === undefined ? fallback : v}`)
  }
  for (const [name, driver] of NULLABLE) {
    const v = r[driver]?.value
    base.push(`${name}: ${v === null || v === undefined ? 'null' : v}`)
  }

  lines.push(
    `  {\n` +
    `    key: '${site.key}', label: '${site.label}', place: '${site.place}',\n` +
    `    base: { ${base.join(', ')} },\n` +
    `  },`,
  )
}

const out = `// GENERATED by scripts/gen-default-sites.mjs from data/regions.json.
// Do not edit by hand. Re-run the script after any change to the dataset.
//
// Nordic Hydro is not on the US map, so it is carried here rather than in
// usRegions. Place names are the only values not read from the dataset.
import type { SiteDrivers } from '../lib/engine'

export interface NamedSite { key: string; label: string; place: string; base: SiteDrivers }

export const DEFAULT_SITES: NamedSite[] = [
${lines.join('\n')}
]
`

writeFileSync(resolve(here, '../src/data/defaultSites.ts'), out)
console.log('Wrote src/data/defaultSites.ts from data/regions.json')
for (const s of SITES) {
  const r = regions[s.key]
  console.log(`  ${s.label.padEnd(20)} build $${r.construction_cost_per_kw.value}/kW  land $${r.land_cost_per_acre_usd.value}/acre  tax ${r.tax_rate.value}  abatement ${r.tax_abatement_years.value}y`)
}

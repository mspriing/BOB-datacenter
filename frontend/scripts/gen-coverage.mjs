// Regenerates src/data/coverage.ts from data/regions.json.
//
// These figures were typed by hand and went stale: the page claimed 259 sourced
// values when the dataset held 304, and carried assumed: 582, which was really
// the count of EMPTY cells from July mislabelled as guesses. A product whose
// argument is that every figure is traceable cannot hand-maintain its own
// traceability count.
//
// Run from the frontend folder:  node scripts/gen-coverage.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const regions = JSON.parse(readFileSync(resolve(here, '../../data/regions.json'), 'utf8'))

// A site cannot be ranked without these four. This mirrors the engine's own
// unevaluable rule, so the number the page shows is the number that can be run.
const REQUIRED = ['construction_cost_per_kw', 'power_rate_usd_per_kwh',
                  'land_cost_per_acre_usd', 'staff_cost_index']

// construction_cost_per_mw is a legacy duplicate of construction_cost_per_kw and
// nothing reads it. Counting it would advertise a fourteenth driver that does not
// exist as far as the engine is concerned.
const LEGACY = new Set(['construction_cost_per_mw'])

let sourced = 0, modeled = 0, assumed = 0, empty = 0, cells = 0
let priceable = 0
const driverNames = new Set()

for (const region of Object.values(regions)) {
  for (const [name, cell] of Object.entries(region)) {
    if (!cell || typeof cell !== 'object' || !('basis' in cell)) continue
    if (LEGACY.has(name)) continue
    driverNames.add(name)
    cells++
    if (cell.value === null || cell.value === undefined) { empty++; continue }
    if (cell.basis === 'sourced') sourced++
    else if (cell.basis === 'modeled') modeled++
    else assumed++
  }
  if (REQUIRED.every(d => region[d] && region[d].value !== null && region[d].value !== undefined)) priceable++
}

// The parcel count the setup card advertises, counted rather than typed, for
// the same reason as everything above. It was written by hand as 3,046, which
// is the number of ROWS the Bexar ingest produced; six of those rows repeat a
// parcel already in the file, either as an identical feature returned twice or
// as a second part of a multi-part parcel carrying the whole parcel's acreage.
// The backend hands out one row per id, so the page counts the same way.
const parcelRows = JSON.parse(readFileSync(resolve(here, '../../data/parcels/bexar.rows.json'), 'utf8'))
const parcels = new Set(parcelRows.map(r => r.parcel_id)).size

const out = {
  regions: Object.keys(regions).length,
  drivers: driverNames.size,
  cells, sourced, modeled, assumed, empty, priceable,
  parcels,
}

writeFileSync(resolve(here, '../src/data/coverage.ts'),
  `// GENERATED by scripts/gen-coverage.mjs from data/regions.json. Do not edit by hand.\n` +
  `// Re-run after any ingest so the page never overstates or understates itself.\n` +
  `export const COVERAGE = ${JSON.stringify(out, null, 2)} as const\n`)

console.log(out)
